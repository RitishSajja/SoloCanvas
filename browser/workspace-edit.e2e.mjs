import { test, expect } from './returning-user-fixture.mjs';
import { openWorkspaceBoard, renameSelectedComponent } from './workspace-helpers.mjs';
test('workspace canvas moves, connects, labels and removes components with persistence', async ({ page }) => {
 await page.goto('/');
 await openWorkspaceBoard(page);
 await page.getByRole('button', { name: 'Add component' }).click();
 await page.getByRole('button', { name: 'Add component' }).click();
 const nodes = page.locator('.react-flow__node');
 await expect(nodes).toHaveCount(2);
 const a = nodes.nth(0); const b = nodes.nth(1);
 const from = await a.locator('.react-flow__handle.source').boundingBox();
 const to = await b.locator('.react-flow__handle.target').boundingBox();
 if (!from || !to) throw new Error('missing handles');
 await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
 await page.mouse.down(); await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 20 }); await page.mouse.up();
 const edge = page.locator('.react-flow__edge').first();
 await expect(page.locator('.react-flow__edge')).toHaveCount(1);
 await expect(edge.locator('.react-flow__edge-path')).toHaveCSS('visibility', 'visible');
 const before = await b.boundingBox(); if (!before) throw new Error('missing node');
 await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2);
 await page.mouse.down();
 await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2 + 80, { steps: 15 });
 await page.mouse.up();
 const after = await b.boundingBox(); if (!after) throw new Error('missing moved node');
 expect(after.y).toBeGreaterThan(before.y + 50);
 await edge.locator('.react-flow__edge-interaction').click({ force: true });
 await page.getByLabel('Relationship label').fill('depends on');
 page.once('dialog', dialog => dialog.accept());
 await page.getByRole('button', { name: 'Save workspace' }).click();
 await expect(page.getByRole('status')).toContainText('Workspace saved');
 await page.reload();
 await openWorkspaceBoard(page);
 await expect(page.locator('.react-flow__node')).toHaveCount(2);
 await expect(page.getByText('depends on', { exact: true })).toBeVisible();
 await page.locator('.react-flow__node').first().click();
 await page.getByRole('button', { name: 'Remove component from board' }).click();
 await expect(page.locator('.react-flow__node')).toHaveCount(1);
 await expect(page.locator('.react-flow__edge')).toHaveCount(0);
 await page.getByRole('button', { name: 'Save workspace' }).click();
 await expect(page.getByRole('status')).toContainText('Workspace saved');
 await page.reload(); await openWorkspaceBoard(page);
 await expect(page.locator('.react-flow__node')).toHaveCount(1);
 await expect(page.locator('.react-flow__edge')).toHaveCount(0);
});

test('removing one placement keeps the shared component on other boards', async ({ page }) => {
 await page.goto('/');
 await openWorkspaceBoard(page);
 await page.getByRole('button', { name: 'Add component' }).click();
 await page.locator('.react-flow__node').first().click();
 await renameSelectedComponent(page, 'Shared');
 page.once('dialog', dialog => dialog.accept('Other board'));
 await page.getByRole('button', { name: 'New board' }).click();
 await page.getByLabel('Existing component').selectOption({ label: 'Shared' });
 await page.getByRole('button', { name: 'Place component' }).click();
 await page.locator('.react-flow__node').first().click();
 await page.getByRole('button', { name: 'Remove component from board' }).click();
 await expect(page.locator('.react-flow__node')).toHaveCount(0);
 await page.getByLabel('Current board').selectOption({ label: 'My board' });
 await expect(page.locator('.react-flow__node').filter({ hasText: 'Shared' })).toBeVisible();
 await page.getByLabel('Current board').selectOption({ label: 'Other board' });
 await page.getByRole('button', { name: 'Place component' }).click();
 page.once('dialog', dialog => dialog.accept());
 await page.getByRole('button', { name: 'Save workspace' }).click();
 await expect(page.getByRole('status')).toContainText('Workspace saved');
 await page.reload(); await openWorkspaceBoard(page);
 await page.getByLabel('Current board').selectOption({ label: 'Other board' });
 await expect(page.locator('.react-flow__node').filter({ hasText: 'Shared' })).toBeVisible();
});
