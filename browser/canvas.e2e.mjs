import { test, expect } from '@playwright/test';

test('create, move, connect, label, save, reload and delete', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Add component' }).click();
  await page.getByLabel('Component name').fill('Service A');
  await page.getByRole('button', { name: 'Add component' }).click();
  await page.getByLabel('Component name').fill('Service B');
  const nodeA = page.locator('.react-flow__node').filter({ hasText: 'Service A' });
  const nodeB = page.locator('.react-flow__node').filter({ hasText: 'Service B' });
  const original = await nodeB.boundingBox();
  if (!original) throw new Error('Second component is not visible');
  await page.mouse.move(original.x + original.width / 2, original.y + original.height / 2);
  await page.mouse.down();
  await page.mouse.move(original.x + original.width / 2 + 180, original.y + original.height / 2 + 140, { steps: 15 });
  await page.mouse.up();
  const moved = await nodeB.boundingBox();
  expect(moved.x).toBeGreaterThan(original.x + 50);
  const source = nodeA.locator('.react-flow__handle.source');
  const target = nodeB.locator('.react-flow__handle.target');
  const from = await source.boundingBox();
  const to = await target.boundingBox();
  if (!from || !to) throw new Error('Connection handles are not visible');
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 20 });
  await page.mouse.up();
  const edge = page.locator('.react-flow__edge').first();
  await expect(edge).toBeVisible();
  await edge.locator('.react-flow__edge-interaction').click({ force: true });
  await page.getByLabel('Relationship label').fill('calls');
  await page.getByRole('button', { name: 'Save board' }).click();
  await expect(page.getByRole('status')).toContainText('Saved on this device');
  await page.reload();
  await expect(page.locator('.react-flow__node')).toHaveCount(2);
  await expect(page.locator('.react-flow__edge')).toHaveCount(1);
  await expect(page.getByText('calls', { exact: true })).toBeVisible();
  await page.locator('.react-flow__node').filter({ hasText: 'Service B' }).click();
  await page.keyboard.press('Delete');
  await expect(page.locator('.react-flow__node')).toHaveCount(1);
  await page.getByRole('button', { name: 'Save board' }).click();
  await page.reload();
  await expect(page.locator('.react-flow__node')).toHaveCount(1);
  await expect(page.locator('.react-flow__edge')).toHaveCount(0);
});
